#!/usr/bin/env node
/* Build src/v3/core/journey-world.js — the Memory Journey's local world map.

   Usage: node scripts/build-world-map.mjs <path-to-countries-110m.json>

   Input: world-atlas@2.0.2 `countries-110m.json` (ISC; the geometry is Natural
   Earth 1:110m, public domain). Fetch it yourself into a scratch directory:
     https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json
   It is NOT vendored: the repo keeps only this script and its output.

   Why local at all: the journey must work with no internet and must not send
   the coordinates of family photographs to a map provider. See journey-geo.js.

   Output format, per country: [name, rings], where each ring is a flat list of
   integers in tenths of a degree, DELTA-encoded after the first point:
     x = round((lon + 180) * 10), y = round((90 - lat) * 10)
   Rings that cross the antimeridian are UNWRAPPED (x may exceed 3600) so a
   polygon never draws a streak across the whole map. Antarctica is dropped. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-world-map.mjs <countries-110m.json>");
  process.exit(2);
}
const topo = JSON.parse(readFileSync(src, "utf8"));
const { scale: [kx, ky], translate: [tx, ty] } = topo.transform;

// Decode the quantised, delta-encoded arcs to [lon, lat].
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * kx + tx, y * ky + ty];
  });
});

function ring(indexes) {
  const pts = [];
  for (const i of indexes) {
    const a = i >= 0 ? arcs[i] : arcs[~i].slice().reverse();
    // Consecutive arcs share their joining point.
    pts.push(...(pts.length ? a.slice(1) : a));
  }
  return pts;
}

function encode(pts) {
  const out = [];
  let px = null;
  let py = null;
  let shift = 0;
  let prevLon = null;
  for (const [lon0, lat] of pts) {
    // Unwrap across the antimeridian relative to the previous point.
    if (prevLon !== null) {
      const d = lon0 + shift - prevLon;
      if (d > 180) shift -= 360;
      else if (d < -180) shift += 360;
    }
    const lon = lon0 + shift;
    prevLon = lon;
    const x = Math.round((lon + 180) * 10);
    const y = Math.round((90 - lat) * 10);
    if (x === px && y === py) continue;
    if (px === null) out.push(x, y);
    else out.push(x - px, y - py);
    px = x;
    py = y;
  }
  return out.length >= 6 ? out : null;
}

const countries = [];
for (const g of topo.objects.countries.geometries) {
  const name = g.properties?.name;
  if (!name || name === "Antarctica") continue;
  const polys = g.type === "Polygon" ? [g.arcs] : g.type === "MultiPolygon" ? g.arcs : [];
  const rings = [];
  // Outer rings only: at 1:110m the holes are lakes and enclaves too small to
  // read on a wall, and an outer-only ring keeps the point-in-polygon honest.
  for (const poly of polys) {
    const r = encode(ring(poly[0]));
    if (r) rings.push(r);
  }
  if (rings.length) countries.push([name, rings]);
}
countries.sort((a, b) => a[0].localeCompare(b[0]));

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "src", "v3", "core", "journey-world.js");
const body =
  "/* GENERATED by scripts/build-world-map.mjs — do not edit by hand.\n" +
  "   Natural Earth 1:110m countries (public domain) via world-atlas@2.0.2 (ISC).\n" +
  "   [name, rings]; each ring is flat ints in tenths of a degree, delta-encoded:\n" +
  "   x = (lon + 180) * 10, y = (90 - lat) * 10. Loaded lazily by journey.js. */\n" +
  `export const COUNTRIES = ${JSON.stringify(countries)};\n`;
writeFileSync(out, body);
console.log(`wrote ${out}: ${countries.length} countries, ${(body.length / 1024).toFixed(1)} KB`);
